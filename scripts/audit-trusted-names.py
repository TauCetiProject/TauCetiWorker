#!/usr/bin/env python3
"""Regenerate tauceti_worker/audit_trusted_names.py from pinned baseline sources.

Usage: scripts/audit-trusted-names.py LEAN_SRC DEP_SRC... > tauceti_worker/audit_trusted_names.py

LEAN_SRC is the pinned toolchain's src/lean directory; each DEP_SRC is a checkout
of a lake-manifest dependency at its pinned revision. The output lists attribute
and syntax keyword names that the trusted baseline defines. Security-audit
reviewers use it only to recognise a construct's origin; it never makes safe a
use the inspection policy flags.
"""

import json
import pathlib
import re
import sys

WORD = re.compile(r"^[A-Za-z_][A-Za-z0-9_!?'.]*$")
ATTRIBUTE = [
    re.compile(r"register_(?:simp|label)_attr\s+([A-Za-z_][\w.]*)"),
    re.compile(r"register(?:Tag|Parametric|Enum|Builtin)?Attribute[^`\n]*`([A-Za-z_][\w.]*)"),
    re.compile(r"registerBuiltinAttribute\s*\{[^}]*?name\s*:=\s*`([A-Za-z_][\w.]*)", re.S),
    re.compile(r"\bname\s*:=\s*`([A-Za-z_][\w.]*)[^}]{0,400}?(?:add|applicationTime|erase)\s*:=", re.S),
    re.compile(r"mk\w*Attr\w*\s+`([A-Za-z_][\w.]*)"),
]
DECLARATION = re.compile(
    r"^\s*(?:@\[[^\]]*\]\s*)?(?:(?:scoped|local)\s+)?(?:syntax|macro|elab|notation|infix[lr]?|prefix|postfix)\b"
    r'(?:\s*:\s*\w+)?(?:\s*\((?:name|priority|kind)\s*:=[^)]*\))*\s*"([^"]+)"'
)
PARSER = re.compile(r'leading_parser(?::\w+)?\s*(?:\(withAnonymousAntiquot := false\)\s*)?"([^"]+)"')


def names(roots):
    found = set()
    for root in roots:
        for path in sorted(pathlib.Path(root).rglob("*.lean")):
            if "/.lake/" in str(path) or "/test" in str(path).lower():
                continue
            text = path.read_text(errors="replace")
            for pattern in ATTRIBUTE:
                found.update(m.group(1) for m in pattern.finditer(text))
            for line in text.splitlines():
                m = DECLARATION.match(line)
                if m:
                    found.add(m.group(1).strip())
                found.update(m.group(1).strip() for m in PARSER.finditer(line))
    return sorted(n for n in found if WORD.match(n))


def main(argv):
    if len(argv) < 2:
        raise SystemExit(__doc__)
    lean = pathlib.Path(argv[0])
    roots = [lean / "Init", lean / "Lean", lean / "Std", *argv[1:]]
    listed = names(roots)
    print('"""Attribute and syntax names defined by the pinned trusted baseline.')
    print("")
    print("Generated by scripts/audit-trusted-names.py; do not edit by hand.")
    print('"""')
    print("")
    print("NAMES = (")
    for name in listed:
        print(f"    {json.dumps(name)},")
    print(")")


if __name__ == "__main__":
    main(sys.argv[1:])
