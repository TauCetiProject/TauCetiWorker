    def start_service(self, *, fresh: bool = True) -> None:
        config = self._service_config(fresh=fresh)
        self.service_url = f"http://127.0.0.1:{self.port}"
        logfile = open(self.workdir / "service" / f"serve-{int(time.time())}.log", "ab")  # noqa: SIM115 - the process owns it
        env = {k: v for k, v in os.environ.items() if not k.startswith("TAUCETI_QUEUE_")}
        env["TAUCETI_QUEUE_CONFIG"] = str(config)
        self.process = subprocess.Popen(
            [sys.executable, "-m", "tauceti_queue", "serve", "--config", str(config)],
            cwd=str(HERE),
            stdout=logfile,
            stderr=subprocess.STDOUT,
            env=env,
        )
        self.facts.setdefault("service_starts", []).append({"pid": self.process.pid, "at": _now_iso()})
        deadline = time.monotonic() + 180
        while True:
            if self.process.poll() is not None:
                raise Failure(f"tauceti-queue serve exited {self.process.returncode}; see {logfile.name}")
            try:
                document = self.status()
                if (document.get("service") or {}).get("controller") == "running":
                    break
            except Exception:  # noqa: BLE001 - not up yet
                pass
            if time.monotonic() > deadline:
                raise Failure(f"the service did not answer /status within 180 s; see {logfile.name}")
            time.sleep(2)
        if fresh:  # the settings persist in the store, so a restart needs no admin call (and no token quota)
            self.admin(
                "/admin/settings",
                {
                    "polling_interval_seconds": 15,
                    "infrastructure_retry_backoff_seconds": 5,
                    "outbox_retry_seconds": 5,
                    "dispatch_timeout_seconds": 900,
                },
            )

    def stop_service(self) -> None:
        if self.process is None:
            return
        if self.process.poll() is None:
            self.process.send_signal(signal.SIGTERM)
            try:
                self.process.wait(timeout=150)
            except subprocess.TimeoutExpired:
                self.process.kill()
                self.process.wait(timeout=30)
        self.facts.setdefault("service_stops", []).append(
            {"pid": self.process.pid, "rc": self.process.returncode, "at": _now_iso()}
        )
        self.process = None

    def restart_service(self) -> None:
        if self.external_service:
            raise Skip("the service is managed outside the rehearsal (--service); restart it by hand to cover this")
        self.stop_service()
        self.start_service(fresh=False)

    def close(self) -> None:
        with contextlib.suppress(Exception):
            self.relay.stop()
        self.facts["relay"] = {
            "deliveries": self.relay.count,
            "events": self.relay.events,
            "errors": self.relay.errors[-5:],
        }
        self.facts["github_client"] = self.client.stats()
        if not self.keep_service:
            with contextlib.suppress(Exception):
                self.stop_service()

