    # -- GitHub facts

    def _inspect_repository(self) -> None:
        status, info = self.client.get_json(f"repos/{self.repository}", tolerate=(404,))
        if status == 404 or not isinstance(info, dict):
            raise Failure(f"{self.repository} does not exist or the App cannot see it (HTTP {status})")
        self.repo_id = int(info["id"])
        self.branch = str(info.get("default_branch") or "main")
        self.facts["repository_id"] = self.repo_id
        self.facts["default_branch"] = self.branch
        self.facts["private"] = bool(info.get("private"))
        installed = self.adapter.installation_repositories()
        self.facts["installation_repositories"] = installed
        if self.repository not in installed:
            raise Failure(
                f"the App installation does not include {self.repository} (it has {installed}); add the repository "
                "to the installation's repository access first"
            )
        _, app = self.client.get_json("app", token=self.app.tokens.jwt())
        registered = dict((app or {}).get("permissions") or {})
        # What the installation actually granted (the token's permissions), which lags the registration
        # until the operator accepts a permission update.
        self.app.tokens.token()
        granted = dict(getattr(self.app.tokens._current, "permissions", {}) or {})  # noqa: SLF001 - the token record
        self.facts["app"] = {
            "id": (app or {}).get("id"),
            "slug": (app or {}).get("slug"),
            "registered_permissions": registered,
            "installation_permissions": granted,
        }
        self.eligibility_available = granted.get("checks") == "write"
        self.eligibility_reason = (
            "published under the queue's own App (installation permission checks: write)"
            if self.eligibility_available
            else f"the installation's `checks` permission is {granted.get('checks')!r} (registration: "
            f"{registered.get('checks')!r}); publishing a check run needs `checks: write` accepted on the installation; "
            "approval fell back to `bors r+` comments"
        )
        _, user = self.client.get_json("user", token=self.operator_token, tolerate=(401, 403))
        if not isinstance(user, dict) or not user.get("login"):
            raise Failure("the operator token does not authenticate (GET /user)")
        self.operator_login = str(user["login"])
        self.facts["operator"] = self.operator_login
        permission = self.adapter.collaborator_permission(self.repository, self.operator_login)
        self.facts["operator_permission"] = permission
        if permission != "admin":
            raise Failure(f"{self.operator_login} needs admin permission on {self.repository} (has {permission!r})")

    def _git_env(self) -> dict[str, str]:
        token = self.app.tokens.token()
        auth = base64.b64encode(f"x-access-token:{token}".encode()).decode("ascii")
        return {
            "GIT_CONFIG_COUNT": "1",
            "GIT_CONFIG_KEY_0": "http.https://github.com/.extraheader",
            "GIT_CONFIG_VALUE_0": f"AUTHORIZATION: basic {auth}",
        }

    def runner_environment(self) -> dict[str, str | None]:
        return dict(self._git_env())

    def _clone(self, target: Path) -> None:
        if target.exists():
            shutil.rmtree(target)
        run_git(
            self.workdir,
            "clone",
            "--quiet",
            f"https://github.com/{self.repository}.git",
            str(target),
            env=self._git_env(),
        )

    def _fetch(self, clone: Path, *refspecs: str) -> None:
        run_git(clone, "fetch", "--quiet", "--no-tags", "origin", *refspecs, env=self._git_env())

    def _push(self, clone: Path, refspec: str) -> None:
        """Push with retries: GitHub's transient 5xx answers must not end a rehearsal scenario."""
        delays = (10, 30, 60, 120, 180)
        for attempt in range(len(delays) + 1):
            try:
                run_git(clone, "push", "--quiet", "origin", refspec, env=self._git_env())
                return
            except RuntimeError as error:
                transient = any(
                    s in str(error)
                    for s in (
                        "Internal Server Error",
                        "500",
                        "502",
                        "503",
                        "timed out",
                        "unexpected disconnect",
                        "RPC failed",
                    )
                )
                if not transient or attempt == len(delays):
                    raise
                log(
                    f"push of {refspec} failed transiently ({str(error).splitlines()[-1][:100]}); retrying in {delays[attempt]}s"
                )
                time.sleep(delays[attempt])

    def ensure_scaffold(self) -> dict:
        """Push the generated content to the default branch unless it is already there at this version."""
        clone = self.content_clone
        try:
            self._fetch(clone, f"+refs/heads/{self.branch}:refs/remotes/origin/{self.branch}")
            tip = run_git(clone, "rev-parse", f"refs/remotes/origin/{self.branch}")
        except RuntimeError:
            tip = None
        wanted = scaffold_files(self.public_url)
        current: dict[str, str | None] = {}
        if tip:
            for name in wanted:
                result = subprocess.run(
                    ["git", "-C", str(clone), "show", f"{tip}:{name}"], capture_output=True, text=True
                )
                current[name] = result.stdout if result.returncode == 0 else None
        stale = [name for name in wanted if name != SHARED_MODULE and current.get(name) != wanted[name]]
        if tip and not stale:
            return {"pushed": False, "tip": tip}
        if tip:
            run_git(clone, "checkout", "--quiet", "--detach", tip)
        else:
            run_git(clone, "checkout", "--quiet", "--orphan", "scaffold")
            run_git(clone, "rm", "-rf", "--quiet", "--ignore-unmatch", ".")
        for name, text in wanted.items():
            if name == SHARED_MODULE and current.get(name):
                continue  # the shared module evolves with every run; only its first version is scaffolded
            path = clone / name
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text)
        run_git(clone, "add", "-A")
        run_git(
            clone,
            "commit",
            "--quiet",
            "-m",
            f"Scaffold the queue rehearsal content (version {SCAFFOLD_VERSION})\n\nGenerated by `python -m tauceti_queue.rehearsal scaffold`.",
        )
        sha = run_git(clone, "rev-parse", "HEAD")
        self._push(clone, f"HEAD:refs/heads/{self.branch}")
        log(f"pushed the scaffold to {self.repository}@{self.branch}: {sha[:12]} ({len(stale)} files refreshed)")
        return {"pushed": True, "tip": sha, "refreshed": stale}

