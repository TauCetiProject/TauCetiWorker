class Content:
    """Names and Lean text for one rehearsal run; every module lives under `TauCeti/R<tag>/`."""

    def __init__(self, tag: str) -> None:
        self.tag = tag
        self.namespace = f"R{tag}"

    def path(self, name: str) -> str:
        return f"TauCeti/{self.namespace}/{name}.lean"

    def module(self, name: str, statement: str, *, proof: str = "rfl", failing: bool = False) -> dict[str, str]:
        marker = f"-- {FAIL_MARKER}: this module is expected to fail the build\n" if failing else ""
        text = (
            f"/-! Rehearsal module {name} of run {self.tag}. -/\n{marker}namespace {self.namespace}\n\n"
            f"theorem {name.lower()} : {statement} := {proof}\n\nend {self.namespace}\n"
        )
        return {self.path(name): text}

    def shared_value(self, current: str, value: int) -> str:
        """The shared module with its conflict region set to `value` (an edit of the top definition)."""
        text = re.sub(r"def sharedValue : Nat := \d+", f"def sharedValue : Nat := {value}", current)
        return re.sub(
            r"theorem sharedValue_eq : sharedValue = \d+", f"theorem sharedValue_eq : sharedValue = {value}", text
        )

    def shared_append(self, current: str, name: str) -> str:
        """The shared module with a fact added below the marker (independent of the conflict region)."""
        marker = "-- Further facts are appended below this line.\n"
        if marker not in current:
            raise Failure(f"{SHARED_MODULE} lost its append marker")
        return current.replace(marker, marker + f"theorem {name} : True := trivial\n", 1)


