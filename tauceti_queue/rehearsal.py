class Relay(threading.Thread):
    """Replays the App's webhook deliveries for the scratch repository into the local service.

    GitHub delivers the App's webhooks to the App's registered URL (the production service), which
    ignores repositories it does not serve. The App API lists every delivery with its payload, so the
    rehearsal replays the scratch repository's deliveries, signed with the same secret, into the
    local instance. Deliveries that exist before the relay starts are never replayed.
    """

    def __init__(self, rig: LiveRig, interval: float = 6.0) -> None:
        super().__init__(name="rehearsal-relay", daemon=True)
        self.rig = rig
        self.interval = interval
        self.stop_event = threading.Event()
        self.seen: set[int] = set()
        self.count = 0
        self.errors: list[str] = []
        self.unavailable: str | None = None
        self.events: dict[str, int] = {}

    def run(self) -> None:
        first = True
        while not self.stop_event.is_set():
            try:
                self.scan(replay=not first)
            except Exception as error:  # noqa: BLE001 - the relay must outlive a transient API failure
                self.errors.append(f"{type(error).__name__}: {error}")
            first = False
            if self.stop_event.wait(self.interval):
                break

    def scan(self, *, replay: bool) -> None:
        client = self.rig.client
        jwt = self.rig.app.tokens.jwt()
        status, items = client.get_json(
            "app/hook/deliveries", params={"per_page": 50}, token=jwt, tolerate=(401, 403, 404)
        )
        if status != 200 or not isinstance(items, list):
            self.unavailable = f"GET /app/hook/deliveries answered {status}"
            return
        self.unavailable = None
        for item in reversed(items):
            if not isinstance(item, dict) or not isinstance(item.get("id"), int) or item["id"] in self.seen:
                continue
            self.seen.add(item["id"])
            if not replay or item.get("repository_id") != self.rig.repo_id:
                continue
            _, detail = client.get_json(f"app/hook/deliveries/{item['id']}", token=jwt)
            request = (detail or {}).get("request") or {}
            payload = request.get("payload")
            headers = {str(k).lower(): v for k, v in (request.get("headers") or {}).items()}
            event = str(headers.get("x-github-event") or item.get("event") or "")
            if not isinstance(payload, dict) or not event:
                continue
            post_webhook(self.rig.service_url, self.rig.secret, event, payload, str(item.get("guid") or item["id"]))
            self.count += 1
            self.events[event] = self.events.get(event, 0) + 1

    def stop(self) -> None:
        self.stop_event.set()


