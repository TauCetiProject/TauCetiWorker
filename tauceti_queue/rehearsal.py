@dataclasses.dataclass
class ScenarioRecord:
    id: str
    title: str
    plan: list[int]  # acceptance scenario numbers of docs/redesign/specs/ai-merge-queue.md
    status: str = "pending"
    detail: str = ""
    evidence: dict[str, Any] = dataclasses.field(default_factory=dict)
    seconds: float = 0.0

    def to_dict(self) -> dict[str, Any]:
        return dataclasses.asdict(self)


class Report:
    def __init__(self, mode: str, repository: str, service_url: str) -> None:
        self.mode = mode
        self.repository = repository
        self.service_url = service_url
        self.started_at = _now_iso()
        self.finished_at: str | None = None
        self.scenarios: list[ScenarioRecord] = []
        self.facts: dict[str, Any] = {}

    @contextlib.contextmanager
    def scenario(self, ident: str, title: str, plan: list[int]):
        record = ScenarioRecord(ident, title, plan)
        self.scenarios.append(record)
        started = time.monotonic()
        log(f"scenario {ident}: {title}")
        try:
            yield record
        except Skip as skip:
            record.status, record.detail = "skip", str(skip)
            log(f"scenario {ident}: skipped: {skip}")
        except (Failure, AssertionError) as failure:
            record.status, record.detail = "fail", str(failure)
            log(f"scenario {ident}: FAILED: {failure}")
        except Exception as error:  # noqa: BLE001 - the report records the failure instead of losing the run
            record.status, record.detail = "fail", f"{type(error).__name__}: {error}"
            record.evidence["traceback"] = traceback.format_exc()
            log(f"scenario {ident}: FAILED: {record.detail}")
        else:
            record.status = "pass"
            log(f"scenario {ident}: pass ({time.monotonic() - started:.0f}s)")
        finally:
            record.seconds = round(time.monotonic() - started, 1)

    def add(self, ident: str, title: str, plan: list[int], status: str, evidence: dict, detail: str = "") -> None:
        self.scenarios.append(ScenarioRecord(ident, title, plan, status, detail, evidence))
        log(f"scenario {ident}: {status}" + (f": {detail}" if detail else ""))

    @property
    def ok(self) -> bool:
        return all(s.status in ("pass", "skip") for s in self.scenarios) and bool(self.scenarios)

    def to_dict(self) -> dict[str, Any]:
        counts = {status: sum(1 for s in self.scenarios if s.status == status) for status in ("pass", "fail", "skip")}
        return {
            "schema": SCHEMA,
            "mode": self.mode,
            "repository": self.repository,
            "service_url": self.service_url,
            "started_at": self.started_at,
            "finished_at": self.finished_at,
            "ok": self.ok,
            "counts": counts,
            "facts": self.facts,
            "scenarios": [s.to_dict() for s in self.scenarios],
        }

    def markdown(self) -> str:
        doc = self.to_dict()
        lines = [
            f"# Queue cutover rehearsal ({self.mode})",
            "",
            f"Repository `{self.repository}`, service `{self.service_url}`, started {self.started_at}, finished {self.finished_at or 'incomplete'}.",
            f"Result: **{'PASS' if self.ok else 'FAIL'}** ({doc['counts']['pass']} passed, {doc['counts']['fail']} failed, {doc['counts']['skip']} skipped).",
            "",
            "| Scenario | Plan scenarios | Status | Seconds | Detail |",
            "| --- | --- | --- | --- | --- |",
        ]
        for s in self.scenarios:
            plan = ", ".join(str(n) for n in s.plan)
            detail = s.detail.replace("|", "\\|").replace("\n", " ")
            lines.append(f"| {s.id}: {s.title} | {plan} | {s.status} | {s.seconds:.0f} | {detail} |")
        if self.facts:
            lines += ["", "## Facts", "", "```json", json.dumps(self.facts, indent=1, default=str), "```"]
        for s in self.scenarios:
            lines += [
                "",
                f"## {s.id}: {s.title}",
                "",
                f"Status: {s.status}." + (f" {s.detail}" if s.detail else ""),
                "",
            ]
            if s.evidence:
                lines += ["```json", json.dumps(s.evidence, indent=1, default=str), "```"]
        return "\n".join(lines) + "\n"

    def write(self, directory: str | os.PathLike[str]) -> tuple[Path, Path]:
        self.finished_at = self.finished_at or _now_iso()
        out = Path(directory)
        out.mkdir(parents=True, exist_ok=True)
        json_path = out / f"rehearsal-{self.mode}.json"
        md_path = out / f"rehearsal-{self.mode}.md"
        json_path.write_text(json.dumps(self.to_dict(), indent=1, default=str) + "\n")
        md_path.write_text(self.markdown())
        return json_path, md_path


