    def _policy(self, head: str, base: str, members) -> tuple[str, list[dict]]:
        if self.next_verdicts:
            verdict = self.next_verdicts.pop(0)
            return verdict, []
        diagnostics = []
        paths = run_git(self.repo.origin, "ls-tree", "-r", "--name-only", head, "--", "TauCeti").split()
        for path in paths:
            text = self.repo.file_at(head, path) or ""
