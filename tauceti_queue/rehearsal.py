def expect(condition: Any, message: str) -> None:
    if not condition:
        raise Failure(message)


def _members(batch: dict | None) -> list[int]:
    return [m["number"] for m in (batch or {}).get("members") or []]


class Rehearsal:
    """The scenario script over a rig; every scenario records its evidence in the report."""

    def __init__(self, rig: Rig, report: Report) -> None:
        self.rig = rig
        self.report = report
        self.content = rig.content
        self.first_run_id: str | None = None
        self.landed: list[dict] = []  # every landed head's snapshot with its chain validation
        self.feed_checks: list[dict] = []
        self.feed_checked_batches: set[int] = set()
        self.eligibility: dict | None = None

    # -- waiting

    def status(self) -> dict:
        return self.rig.status()

    def wait(self, predicate: Callable[[dict], Any], what: str, timeout: float | None = None) -> Any:
        deadline = time.monotonic() + (timeout or self.rig.timeout)
        last: dict = {}
        while True:
            self.rig.drive()
            last = self.status()
            result = predicate(last)
            if result:
                return result
            if time.monotonic() > deadline:
                head = last.get("head") or {}
                raise Failure(
                    f"timed out after {timeout or self.rig.timeout:.0f}s waiting for {what}; head={head.get('id')} "
                    f"v{head.get('version')} stage={head.get('stage')} ci={(head.get('ci') or {}).get('outcome_detail')} "
                    f"reasons={last.get('reasons')} alerts={last.get('alerts')}"
                )
            time.sleep(self.rig.poll)

    def wait_member(self, pr: PR, what: str = "") -> dict:
        """Until the PR is a member of the head or the open batch; returns that batch's status."""

        def predicate(status: dict):
            for batch in (status.get("head"), status.get("open_batch")):
                if batch and pr.number in _members(batch):
                    return batch
            return None

        return self.wait(predicate, what or f"#{pr.number} to be inserted")

    def wait_head_with(self, pr: PR) -> dict:
        return self.wait(
            lambda s: s.get("head") if s.get("head") and pr.number in _members(s["head"]) else None,
            f"a head containing #{pr.number}",
        )

    def wait_stage(self, batch_id: int, stage: str, timeout: float | None = None) -> dict:
        return self.wait(
            lambda s: (
                s.get("head") if s.get("head") and s["head"]["id"] == batch_id and s["head"]["stage"] == stage else None
            ),
            f"head {batch_id} to reach stage {stage}",
            timeout,
        )

    def wait_run(self, batch_id: int, *, started: bool = False) -> dict:
        """Until the head's current CI attempt is bound to a run (and, if asked, that run has started)."""

        def predicate(status: dict):
            head = status.get("head")
            if head is None or head["id"] != batch_id:
                # Live builds can finish inside one service poll; waiting hours for a run of a head that
                # already landed is the wrong failure.
                raise Failure(
                    f"head {batch_id} left the queue before its run was observed {'running' if started else 'bound'}"
                )
            if not head.get("ci"):
                return None
            ci = head["ci"]
            if ci["outcome"] != "pending" or not ci["run_id"]:
                return None
            if started and ci["status"] not in ("in_progress", "completed"):
                return None
            return head

        return self.wait(
            predicate, f"head {batch_id} to have a {'running' if started else 'bound'} CI run", self.rig.ci_timeout
        )

    def wait_landed(self, batch_id: int, snapshot: dict | None = None) -> dict:
        """Until head `batch_id` is gone, the canonical branch is at its last tip and publication is done.

        `snapshot` is the caller's last observation of the head, for a build that may complete before
        the next status poll; every later observation replaces it.
        """
        snapshot = dict(snapshot or {})

        def predicate(status: dict):
            nonlocal snapshot
            head = status.get("head")
            if head and head["id"] == batch_id:
                snapshot = head
                if head["stage"] == "ci" and batch_id not in self.feed_checked_batches:
                    self.feed_checked_batches.add(batch_id)
                    self.check_feeds(f"during the CI run of head {batch_id}")
                return None
            return status

        self.wait(predicate, f"head {batch_id} to land", self.rig.ci_timeout)
        expect(snapshot, f"head {batch_id} was never observed before it disappeared")
        status = self.wait(
            lambda s: (
                s
                if s.get("canonical_sha") == snapshot["tip"] and (s.get("outbox") or {}).get("pending", 1) == 0
                else None
            ),
            f"the canonical branch to reach {snapshot['tip'][:12]} and publication to finish",
        )
        expect(
            self.rig.main_sha() == snapshot["tip"],
            f"GitHub's {self.rig.branch} is not at the landed tip {snapshot['tip'][:12]}",
        )
        landed = {
            "batch_id": batch_id,
            "version": snapshot["version"],
            "base": snapshot["base"],
            "tip": snapshot["tip"],
            "members": snapshot["members"],
            "ci": {
                k: (snapshot.get("ci") or {}).get(k)
                for k in ("run_id", "html_url", "runner", "host", "conclusion", "outcome", "infrastructure_retry")
            },
            "counters": status.get("counters"),
        }
        # The verdict that landed it, from the controller's journal rather than the last snapshot (which may
        # predate the pass): the candidates feed publishes the `ci-pass` entry with its run id.
        passes = self.batch_events(batch_id, "ci-pass")
        expect(passes, f"head {batch_id} landed without a ci-pass journal entry")
        landed["ci"]["pass_event"] = passes[-1]
        landed["ci"]["pass_run_id"] = (passes[-1].get("details") or {}).get("run_id")
        landed["ci"]["run_id"] = landed["ci"]["run_id"] or landed["ci"]["pass_run_id"]
        landed["chain"] = self.check_chain(landed)
        self.landed.append(landed)
        log(f"head {batch_id} v{snapshot['version']} landed at {snapshot['tip'][:12]} (run {landed['ci']['run_id']})")
        return landed

    def land_all(self, prs: list[PR]) -> dict[int, dict]:
        """Follow every PR to its landing; returns each PR's landed head."""
        result: dict[int, dict] = {}
        pending = {pr.number: pr for pr in prs}
        while pending:
            for landed in self.landed:  # heads that landed earlier may already carry some of them
                for number in _members(landed):
                    if number in pending:
                        result[number] = landed
                        pending.pop(number)
            if not pending:
                break
            head = self.wait(lambda s: s.get("head"), f"a head while {sorted(pending)} wait")
            landed = self.wait_landed(head["id"], head)
            for number in _members(landed):
                if number in pending:
                    result[number] = landed
                    pending.pop(number)
        return result

    # -- checks

    def check_chain(self, landed: dict) -> dict:
        members = [m["source_pr"] for m in landed["members"]]
        report = self.rig.validate_chain(landed["base"], landed["tip"], members)
        expect(report["ok"], f"chain validation of head {landed['batch_id']} failed: {report['violations']}")
        expect(report["commit_count"] == len(members), "one commit per member")
        for commit in report["commits"]:
            expect(commit.get("source_pr") in members, f"commit {commit.get('sha')} names an unknown member")
        return {"ok": True, "commits": report["commits"], "members": members}

    def check_feeds(self, where: str) -> dict:
        schema = feeds.load_schema()
        observation = self.rig.feed("active-batches")
        candidates = self.rig.feed("candidates")
        promoted = self.rig.feed("candidates", promoted="true")
        errors = (
            feeds.validate_observation(observation, schema)
            + feeds.validate_candidates(candidates, schema)
            + feeds.validate_candidates(promoted, schema)
        )
        record = {
            "where": where,
            "errors": errors,
            "batch_ids": observation.get("batch_ids"),
            "batch_states": [b.get("state") for b in observation.get("batches") or []],
            "candidates": len(candidates.get("candidates") or []),
            "promoted": len(promoted.get("candidates") or []),
        }
        self.feed_checks.append(record)
        return record

    def batch_events(self, batch_id: int, kind: str) -> list[dict]:
        """The controller's journal entries of one batch, as the candidates feed publishes them."""
        found = []
        for which in ({}, {"promoted": "true"}):
            document = self.rig.feed("candidates", batch_id=str(batch_id), **which)
            for candidate in document.get("candidates") or []:
                for event in candidate.get("events") or []:
                    if event.get("kind") == kind and event not in found:
                        found.append(event)
        return found

    def pr_evidence(self, pr: PR, *, edited: bool | None = None, mentions: str | None = None) -> dict:
        record = self.rig.pr_record(pr.number)
        comment = self.rig.landing_comment(pr.number)
        expect(comment is not None, f"#{pr.number} has no landing comment")
        body = comment["body"]
        expect(
            "Pull request successfully merged into" in body, f"#{pr.number}: the landing comment lacks Bors's notice"
        )
        if edited is True:
            expect(
                "edited this contribution" in body,
                f"#{pr.number}: the comment does not say the contribution was edited",
            )
        if edited is False:
            expect("edited this contribution" not in body, f"#{pr.number}: a clean member got an edit comment")
        if mentions:
            expect(mentions in body, f"#{pr.number}: the comment does not quote {mentions!r}")
        return {
            "number": pr.number,
            "accepted_head": pr.head,
            "state": record["state"],
            "title": record["title"],
            "comment_id": comment["id"],
            "comment_url": comment.get("html_url"),
            "comment_excerpt": body.splitlines()[0][:120],
        }

    def expect_closed_by_queue(self, pr: PR, evidence: dict) -> None:
        expect(evidence["state"] == "closed", f"#{pr.number} is not closed")
        expect(evidence["title"].startswith(MERGED_TITLE_PREFIX), f"#{pr.number} title lacks {MERGED_TITLE_PREFIX!r}")

    def approve(self, pr: PR, *, via: str = "comment") -> dict:
        evidence = self.rig.approve(pr, via=via)
        log(f"approved #{pr.number} via {via}")
        return evidence

    def agent(self, plan: dict | None, **kwargs) -> dict:
        outcome = self.rig.run_agent(plan, **kwargs)
        return {
            k: outcome.get(k)
            for k in (
                "task_id",
                "status",
                "reason",
                "detail",
                "tip",
                "version",
                "pushed_ref",
                "worker",
                "seconds",
                "lease",
            )
        }

